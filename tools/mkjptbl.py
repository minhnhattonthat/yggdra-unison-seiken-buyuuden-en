"""mkjptbl.py: write tbl/jp.tbl (FONT_MES glyph order) from the readings below. Kanji readings: tbl/kanji.tsv (glyph hex, char).

Text code -> glyph: byte < 0xF0 is glyph b; 0xF1+n, xx is glyph 0xF0 + n*0x100 + xx (see docs/re/text.md).
Unread glyphs are written as {g:XXX} so every code stays round-trippable.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NGLYPH = 0x56E

# Glyph order, read off work/font_mes*.png (verified against decoded MESSAGE085/SPMES002003 lines).
KANA = ("あいうえおかきくけこさしすせそたちつてとなにぬねのはひふへほまみむめもやゆよらりるれろわをん"
        "がぎぐげござじずぜぞだぢづでどばびぶべぼぱぴぷぺぽぁぃぅぇぉっゃゅょ")
KATA = ("アイウエオカキクケコサシスセソタチツテトナニヌネノハヒフヘホマミムメモヤユヨラリルレロワヲン"
        "ガギグゲゴザジズゼゾダヂヅデドバビブベボパピプペポァィゥェォッャュョ")
ASCII = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz"


def glyph_chars():
    chars = {}
    for i, c in enumerate(KANA):
        chars[i] = c
    for i, c in enumerate(KATA):
        chars[0x50 + i] = c
    for i, c in enumerate(ASCII):
        chars[0xA0 + i] = c
    for i, c in enumerate("!?♪~「」()…ー。、"):
        chars[0xE0 + i] = c
    kt = ROOT / "tbl/kanji.tsv"
    if kt.exists():
        for line in kt.read_text(encoding="utf-8").splitlines():
            if line and not line.startswith("#"):
                g, c = line.split("\t")[:2]
                if c:
                    chars[int(g, 16)] = c
    return chars


def sys_chars():
    """FONT_SYSTEM order (menus/system text in arm9 and overlays): kana as FONT_MES except ヂヅ -> ・ and a blank,
    then ヴ ー before the digits; kanji from tbl/kanji_sys.tsv."""
    chars = {i: c for i, c in enumerate(KANA)}
    kata = KATA.replace("ヂ", "・").replace("ヅ", "　")
    chars.update({0x50 + i: c for i, c in enumerate(kata)})
    chars.update({0xA0 + i: c for i, c in enumerate("ヴー" + ASCII + "!?♪~「」()…—。、")})
    kt = ROOT / "tbl/kanji_sys.tsv"
    if kt.exists():
        for line in kt.read_text(encoding="utf-8").splitlines():
            if line and not line.startswith("#"):
                g, c = line.split("\t")[:2]
                if c:
                    chars[int(g, 16)] = c
    return chars


def code_of(g):
    return f"{g:02X}" if g < 0xF0 else f"{0xF1 + (g - 0xF0) // 0x100:02X}{(g - 0xF0) % 0x100:02X}"


def main():
    chars = glyph_chars()
    lines = ["# Yggdra Unison DS: text code = FONT_MES glyph. Generated by tools/mkjptbl.py; edit that, not this."]
    for g in range(NGLYPH):
        lines.append(f"{code_of(g)}={chars.get(g, '{g:%03X}' % g)}")
    (ROOT / "tbl").mkdir(exist_ok=True)
    (ROOT / "tbl/jp.tbl").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"tbl/jp.tbl: {NGLYPH} codes, {len(chars)} read")


if __name__ == "__main__":
    main()
