"""mkjptbl.py: write the three text tables from the fonts and the kanji readings.

    python -X utf8 tools/mkjptbl.py     -> tbl/jp.tbl (FONT_MES), tbl/jp_sys.tbl (FONT_SYSTEM), tbl/jp_end.tbl (FONT_END),
                                           tbl/jp_item.tbl (FONT_ITEM)

Text code -> glyph (arm9 0x02012AF4): byte < 0xF0 is glyph b; F1..F9, xx is glyph (b - 0xF0) * 0xF0 + xx.
FD = new line, FC xx = colour (xx indexes the table at 0x0209281C), FF = end. See docs/re/text.md.
Glyphs 00-EB share one layout in every font (KANA, KATA, LATIN below); kanji from EC differ per font and are read
once per bitmap: tbl/kanji.tsv (bitmap key, char, where first read), so a reading made in one font fills every font
holding the same pixels. Glyphs with no reading are written as 〔font:XXX〕 so every code still round-trips.
"""
import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FONTS = {"mes": "FONT_MES.NTFT", "sys": "FONT_SYSTEM.NTFT", "end": "FONT_END.NTFT", "item": "FONT_ITEM.NTFT"}
TABLES = {"mes": "tbl/jp.tbl", "sys": "tbl/jp_sys.tbl", "end": "tbl/jp_end.tbl", "item": "tbl/jp_item.tbl"}
FIRST_KANJI = 0xEC
# FONT_ITEM (bold item names, arm9 item record field +C) has no fixed kana block: every glyph, kana too, is read
# per bitmap (taken from the FONT_SYSTEM name in field +8 of the same record; docs/re/text.md).
NO_LAYOUT = {"item"}


def first_read(font):
    return 0 if font in NO_LAYOUT else FIRST_KANJI

# Glyph order 00-EB, the same in all three fonts (read off glyph sheets; verified in game: tutorial and menus).
KANA = ("あいうえおかきくけこさしすせそたちつてとなにぬねのはひふへほまみむめもやゆよらりるれろわをん"
        "がぎぐげござじずぜぞだぢづでどばびぶべぼぱぴぷぺぽぁぃぅぇぉっゃゅょ")
KATA = ("アイウエオカキクケコサシスセソタチツテトナニヌネノハヒフヘホマミムメモヤユヨラリルレロワヲン"
        "ガギグゲゴザジズゼゾダ・　デドバビブベボパピプペポァィゥェォッャュョ")  # ヂ ヅ slots hold ・ and a blank
LATIN = "ヴー0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz!?♪~「」()…—。、"


def key(raw):
    return hashlib.sha1(raw).hexdigest()[:12]


def readings():
    out = {}
    p = ROOT / "tbl/kanji.tsv"
    if p.exists():
        for line in p.read_text(encoding="utf-8").splitlines():
            if line and not line.startswith("#"):
                k, c = line.split("\t")[:2]
                if c:
                    out[k] = c
    return out


def font_bytes(font):
    p = ROOT / "work/sfs" / FONTS[font]
    if p.exists():
        return p.read_bytes()
    import text  # the ROM, when work/ is gone
    return text.sfs_files([FONTS[font]])[FONTS[font]]


def chars(font, data=None):
    """{glyph: char} for one font; unread kanji are absent."""
    data = font_bytes(font) if data is None else data
    out = {}
    if font not in NO_LAYOUT:
        out = {i: c for i, c in enumerate(KANA)}
        out.update({0x50 + i: c for i, c in enumerate(KATA)})
        out.update({0xA0 + i: c for i, c in enumerate(LATIN)})
    rd = readings()
    for g in range(first_read(font), len(data) // 128):
        c = rd.get(key(data[g * 128:(g + 1) * 128]))
        if c:
            out[g] = c
    return out


def code_of(g):
    return f"{g:02X}" if g < 0xF0 else f"{0xF0 + g // 0xF0:02X}{g % 0xF0:02X}"


def table_lines(font, data=None):
    data = font_bytes(font) if data is None else data
    ch = chars(font, data)
    lines = [f"# Yggdra Unison DS, {FONTS[font]} order. Generated by tools/mkjptbl.py; edit that or tbl/kanji.tsv."]
    seen = {}
    for g in range(len(data) // 128):
        c = ch.get(g, f"〔{font}:{g:03X}〕")
        n = seen[c] = seen.get(c, -1) + 1
        # a font holding one char twice: later copies get a variation selector, so decode shows the char and
        # encode(decode) still gives the original code (plain char -> first copy)
        lines.append(f"{code_of(g)}={c}{chr(0xFE00 + n - 1) if n else ''}")
